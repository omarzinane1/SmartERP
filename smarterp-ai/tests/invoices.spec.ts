test('critical partial overdue invoice contributes only 12800 to a single aging bucket, with overdue independent of payment', () => {
  expect(remainingAmount(critical)).toBe(12800)
  expect(daysOverdue(critical, '2026-09-23')).toBe(8)
  expect(presentation(critical, '2026-09-23')).toBe('overdue')
  expect(critical.paymentStatus).toBe('partially_paid')
  const buckets = calculateAging([critical], '2026-09-23')
  expect(buckets.filter((bucket) => bucket.count)).toEqual([{ key: '1-30', label: '1–30 jours', count: 1, amount: 12800 }])
  expect(invoiceKPIs([critical, { ...critical, id: 1, workflowStatus: 'draft' }, { ...critical, id: 2, workflowStatus: 'cancelled' }], '2026-09-23')).toEqual({ invoiced: 24600, paid: 11800, remaining: 12800, overdue: 12800, overdueCount: 1 })
})
test('aging boundaries include today as current, exclude paid/draft/cancelled and reconcile every mock balance', () => {
  for (const [dueDate, expected] of [['2026-09-30', 'current'], ['2026-10-01', 'current'], ['2026-09-29', '1-30'], ['2026-08-31', '1-30'], ['2026-08-30', '31-60'], ['2026-08-01', '31-60'], ['2026-07-31', '61-90'], ['2026-07-02', '61-90'], ['2026-07-01', '90+']]) expect(agingKey({ ...critical, dueDate }, referenceDate)).toBe(expected)
  expect(daysOverdue({ ...critical, dueDate: referenceDate }, referenceDate)).toBe(0)
  for (const invoice of [{ ...critical, paidAmount: 24600, paymentStatus: 'paid' as const }, { ...critical, workflowStatus: 'draft' as const }, { ...critical, workflowStatus: 'cancelled' as const }]) expect(agingKey(invoice, referenceDate)).toBeNull()
  const aging = calculateAging(invoicesMock, referenceDate)
  expect(sumMoney(aging.map((bucket) => bucket.amount))).toBe(invoiceKPIs(invoicesMock, referenceDate).remaining)
  for (const invoice of invoicesMock) {
    expect(calculateTotals(invoice.lines)).toEqual(invoice.totals)
    expect(invoice.totalAmount).toBe(invoice.totals.total)
    expect(sumMoney(invoice.payments.filter((payment) => payment.status === 'confirmed').map((payment) => payment.amount))).toBe(invoice.paidAmount)
  }
})
test('invoice and payment schemas reject invalid values and combined filtering uses remaining balances', () => {
  const input = toInvoiceInput(draft)
  expect(invoiceSchema.safeParse(input).success).toBe(true)
  for (const patch of [{ customerId: 0 }, { lines: [] }, { dueDate: '2026-01-01' }, { invoiceDate: 'invalid' }]) expect(invoiceSchema.safeParse({ ...input, ...patch }).success).toBe(false)
  for (const amount of [-1, 0, 12800.01, 0.001, NaN]) expect(paymentSchema(12800).safeParse({ date: referenceDate, amount, method: 'Virement bancaire', reference: '', note: '' }).success).toBe(false)
  expect(paymentSchema(12800).safeParse({ date: referenceDate, amount: 12800, method: 'Virement bancaire', reference: '', note: '' }).success).toBe(true)
  expect(filterInvoices([critical], { ...defaultInvoiceFilters, search: 'nova', quick: 'overdue', payment: 'partially_paid', aging: '1-30' }, referenceDate)).toHaveLength(1)
})

